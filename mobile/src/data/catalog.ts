const history = (base: number, wobble: number[]): PricePoint[] =>
  wobble.map((offset, index) => ({
    date: new Date(Date.now() - (wobble.length - 1 - index) * 86400000 * 7).toISOString().slice(0, 10),
    price: Math.max(8, Math.round(base + offset)),
  }))

